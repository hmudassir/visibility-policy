create table collections (
	id bigint generated by default as identity primary key,
	name varchar(120) not null,
	status varchar(20) not null
);

create table documents (
	id bigint generated by default as identity primary key,
	collection_id bigint not null,
	title varchar(200) not null,
	status varchar(20) not null,
	visibility varchar(20) not null,
	constraint documents_collection_fk foreign key (collection_id) references collections (id)
);

create table access_grants (
	id bigint generated by default as identity primary key,
	document_id bigint not null,
	member_name varchar(80) not null,
	constraint access_grants_document_fk foreign key (document_id) references documents (id),
	constraint access_grants_member_uk unique (document_id, member_name)
);

